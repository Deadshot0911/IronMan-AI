create table if not exists public.jarvis_users (
    id bigint generated by default as identity primary key,
    username text not null,
    username_key text not null unique,
    role text not null check (role in ('admin', 'user')),
    pin_salt bytea not null,
    pin_hash bytea not null,
    active boolean not null default true,
    failed_attempts integer not null default 0,
    locked_until double precision not null default 0,
    memory_enabled boolean not null default false,
    memory_json jsonb not null default '[]'::jsonb,
    gender text check (gender in ('male', 'female', 'non_binary', 'prefer_not_to_say')),
    created_at timestamptz not null default now()
);

create table if not exists public.jarvis_sessions (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.jarvis_users(id),
    started_at timestamptz not null default now(),
    ended_at timestamptz,
    archived boolean not null default false
);

create index if not exists jarvis_sessions_user_started
    on public.jarvis_sessions (user_id, started_at desc);

create table if not exists public.jarvis_messages (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.jarvis_users(id),
    session_id bigint not null references public.jarvis_sessions(id),
    message_key text not null,
    role text not null check (role in ('user', 'assistant')),
    content text not null,
    updated_at timestamptz not null default now(),
    unique (session_id, message_key)
);

create table if not exists public.jarvis_user_events (
    id bigint generated by default as identity primary key,
    username text not null,
    action text not null check (action in ('disabled', 'enabled', 'deleted')),
    created_at timestamptz not null default now()
);

create index if not exists jarvis_messages_user_id
    on public.jarvis_messages (user_id, id);

alter table public.jarvis_users enable row level security;
alter table public.jarvis_sessions enable row level security;
alter table public.jarvis_messages enable row level security;
alter table public.jarvis_user_events enable row level security;

revoke all on public.jarvis_users from anon, authenticated;
revoke all on public.jarvis_sessions from anon, authenticated;
revoke all on public.jarvis_messages from anon, authenticated;
revoke all on public.jarvis_user_events from anon, authenticated;

grant all on public.jarvis_users to service_role;
grant all on public.jarvis_sessions to service_role;
grant all on public.jarvis_messages to service_role;
grant all on public.jarvis_user_events to service_role;
grant usage, select on all sequences in schema public to service_role;
